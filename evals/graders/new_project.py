def main(program: str, checks: dict[str, Callable[[], list[str]]], argv: list[str]) -> int:
    """Run the one check `argv` names; exit 0 where it holds, 1 printing why not, 2 on usage."""

    if len(argv) != 1 or argv[0] not in checks:
        print(f"usage: {program} {{{','.join(checks)}}}")
        return 2
    try:
        lacking = checks[argv[0]]()
    except Exception as problem:  # a broken workspace is a failed claim, never a crash
        lacking = [f"the check could not run: {type(problem).__name__}: {problem}"]
    for reason in lacking:
        print(reason)
    return 1 if lacking else 0


