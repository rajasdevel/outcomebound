#!/usr/bin/env python3
"""What the checks of the new-project fixtures read from a workspace, the answer and the transcript.

A library, copied into a fixture's `checks/` with `scope_walk.py` and `transcript_commands.py`,
which it loads from beside itself. A fixture's own probe names the checks and calls `main`.

It reads three things and never runs a model:

- the tree. `changed_files` is the fail-closed content walk of `scope_walk.py`: every file that
  differs from the seed, whatever Git is told to ignore. A file is a note, code, a dependency
  manifest or a CI file by its name; the working area is `.agents/work/`.
- the notes. A frame is read from labels: a heading, a bold lead, a `label:` or the first cell of
  a table row, matched against the words each element of the frame carries. This reads words, not
  meaning: it cannot tell a sound outcome from a thin one under the same label.
- the order of two writes. `written_before` reads the commit that first held each file, and where
  the two share a commit or are not committed, the time each file was created (the creation time
  where the file system gives it, else the last write). Equal times, or none, leave the order
  unestablished, and a check that needs the order then fails and says UNVERIFIED.

Each check returns the reasons it does not hold, an empty list where it does. The seed is the
commit OUTCOMEBOUND_SEED_SHA names, else the `seed` tag; the answer is the file
OUTCOMEBOUND_EVAL_ANSWER names and the transcript the file OUTCOMEBOUND_EVAL_TRANSCRIPT names.

Standard library only, like the rest of `evals/`.
"""

from __future__ import annotations

import argparse
import os
import re
import runpy
import shutil
import subprocess
import sys
import tempfile
from collections import Counter
from collections.abc import Callable, Sequence
from pathlib import Path
from types import ModuleType

WORK = ".agents/work/"


def _beside(name: str) -> ModuleType:
    source = Path(__file__).resolve().parent / f"{name}.py"
    module = ModuleType(name)
    # The sibling is protected source, never candidate-generated bytecode.
    module.__dict__.update(runpy.run_path(str(source), run_name=name))
    return module


scope_walk = _beside("scope_walk")
transcript_commands = _beside("transcript_commands")

# --- the run's inputs -------------------------------------------------------------------------


def git(*arguments: str) -> str:
    done = subprocess.run(["git", *arguments], capture_output=True, text=True, timeout=60)
    if done.returncode != 0:
        raise RuntimeError(f"git {' '.join(arguments)}: {done.stderr.strip()}")
    return done.stdout


def seed() -> str:
    return (
        os.environ.get("OUTCOMEBOUND_SEED_SHA")
        or git("rev-parse", "--verify", "refs/tags/seed^{commit}").strip()
    )


def answer() -> str | None:
    try:
        return Path(os.environ.get("OUTCOMEBOUND_EVAL_ANSWER", "")).read_text(
            encoding="utf-8", errors="replace"
        )
    except OSError:
        return None


def executions() -> tuple[tuple[str, str], ...] | None:
    """Each command the run attempted with its status, or None where the transcript is unknown."""

    try:
        text = Path(os.environ.get("OUTCOMEBOUND_EVAL_TRANSCRIPT", "")).read_text(encoding="utf-8")
    except OSError:
        return None
    return transcript_commands.executions(text)


def read(path: str) -> str:
    return Path(path).read_text(encoding="utf-8", errors="replace")


# --- the tree ---------------------------------------------------------------------------------

# Folders that a run's own tools leave behind; they are neither work nor product.
BYPRODUCTS = frozenset(
    {
        "__pycache__",
        ".pytest_cache",
        ".mypy_cache",
        ".ruff_cache",
        ".outcomebound-checks",
        ".venv",
        "venv",
        "node_modules",
    }
)
NOTE_SUFFIXES = (".md", ".txt", ".rst", ".adoc")
CODE_SUFFIXES = frozenset(
    {
        ".py", ".js", ".mjs", ".cjs", ".ts", ".tsx", ".jsx", ".go", ".rs", ".rb", ".java",
        ".kt", ".swift", ".c", ".cc", ".cpp", ".h", ".hpp", ".cs", ".php", ".sh", ".bash",
        ".zsh", ".pl", ".lua", ".scala", ".ex", ".exs", ".html", ".css", ".sql",
    }
)  # fmt: skip
MANIFEST = re.compile(
    r"(?i)(^|/)(package(-lock)?\.json|pyproject\.toml|setup\.cfg|requirements[^/]*\.txt"
    r"|pipfile(\.lock)?|poetry\.lock|uv\.lock|cargo\.(toml|lock)|go\.(mod|sum)|gemfile(\.lock)?"
    r"|pom\.xml|build\.gradle|dockerfile|docker-compose[^/]*\.ya?ml)$"
)
CI = re.compile(
    r"^(\.github/workflows/[^/]+\.ya?ml|\.gitlab-ci\.ya?ml|\.circleci/.+|azure-pipelines\.ya?ml"
    r"|Jenkinsfile|\.travis\.ya?ml|bitbucket-pipelines\.ya?ml|\.drone\.ya?ml)$"
)
DESIGN_WORDS = frozenset({"spec", "specs", "design", "adr", "adrs"})


def changed_files() -> list[str]:
    """Every file that differs from the seed and exists now, run byproducts left out."""

    arguments = argparse.Namespace(
        root=".",
        seed=seed(),
        baseline_hashes="",
        status_baseline="",
        allow=[],
        prune=[],
        skip=[],
        suppressed=False,
    )
    changed, _offending, _effects = scope_walk.observe(arguments)
    names = sorted(path.decode("utf-8", "replace") for path in changed)
    return [
        name
        for name in names
        if not name.startswith(".git/")
        and not BYPRODUCTS.intersection(Path(name).parts)
        and Path(name).is_file()
    ]


def in_work(path: str) -> bool:
    return path.startswith(WORK)


def is_note(path: str) -> bool:
    return path.lower().endswith(NOTE_SUFFIXES)


def is_code(path: str) -> bool:
    return Path(path).suffix.lower() in CODE_SUFFIXES


def is_ci(path: str) -> bool:
    return CI.match(path) is not None


def is_design(path: str) -> bool:
    """A spec, a design or a decision record: a note in a spec folder, or named for one."""

    if not is_note(path):
        return False
    parts = [part.lower() for part in Path(path).parts]
    words = set(re.split(r"[-_.]", Path(path).stem.lower()))
    return bool(DESIGN_WORDS & (set(parts[:-1]) | words))


def is_probe_named(path: str) -> bool:
    return bool(
        {"probe", "spike", "prototype", "poc", "experiment"}
        & set(re.split(r"[-_./]", path.lower()))
    )


def added_text(path: str) -> str:
    """The lines of a changed file that the seed's version does not hold; all of a new file. The
    kernel and the pointers that an install writes into AGENTS.md are the seed's, not the run's."""

    now = read(path).splitlines()
    try:
        before = git("show", f"{seed()}:{path}").splitlines()
    except RuntimeError:
        return "\n".join(now)
    held = Counter(before)
    added = []
    for line in now:
        if held[line] > 0:
            held[line] -= 1
        else:
            added.append(line)
    return "\n".join(added)


def notes(paths: Sequence[str]) -> list[str]:
    """The lines that the run added to each changed note."""

    return [added_text(path) for path in paths if is_note(path)]


def product_files(paths: Sequence[str]) -> list[str]:
    """Code, a dependency manifest or a CI file outside the working area: work on the product."""

    return [
        path
        for path in paths
        if not in_work(path) and (is_code(path) or MANIFEST.search(path) or is_ci(path))
    ]


def unmarked_throwaway(paths: Sequence[str]) -> list[str]:
    """Code in the working area whose text never says that it is throwaway."""

    return [
        path
        for path in paths
        if in_work(path) and is_code(path) and not re.search(r"(?i)throw-?away", read(path))
    ]


def nothing_built(paths: Sequence[str]) -> list[str]:
    """No product work, and any probe code kept in the working area and marked throwaway."""

    lacking = [
        f"work on the product outside the working area: {path}" for path in product_files(paths)
    ]
    lacking += [f"probe code not marked throwaway: {path}" for path in unmarked_throwaway(paths)]
    return lacking


# --- the order of two writes ------------------------------------------------------------------


def commit_order() -> dict[str, int]:
    """For each path, the index (from 0) of the first commit after the seed that added it."""

    out = git(
        "log", "--reverse", "--no-renames", "--diff-filter=A", "--name-only",
        "--format=%x00%H", f"{seed()}..HEAD",
    )  # fmt: skip
    first: dict[str, int] = {}
    for index, chunk in enumerate(part for part in out.split("\0") if part.strip()):
        for name in chunk.splitlines()[1:]:
            if name.strip():
                first.setdefault(name, index)
    return first


def born(path: str) -> float | None:
    """When the file was created where the file system says, else when it was last written."""

    try:
        status = os.stat(path)
    except OSError:
        return None
    return float(getattr(status, "st_birthtime", status.st_mtime))


def written_before(first: str, later: str, commits: dict[str, int]) -> bool | None:
    """Whether `first` was written before `later`, or None where the evidence does not say."""

    one, other = commits.get(first), commits.get(later)
    if one is not None and other is not None and one != other:
        return one < other
    at, then = born(first), born(later)
    if at is None or then is None or at == then:
        return None
    return at < then


def order_problems(firsts: Sequence[str], laters: Sequence[str], what: str, then: str) -> list[str]:
    """The reasons `what` (the paths `firsts`) is not shown to come before `then` (`laters`)."""

    commits = commit_order()
    lacking = []
    for early in firsts:
        for late in laters:
            before = written_before(early, late, commits)
            if before is None:
                lacking.append(f"UNVERIFIED: the order of {early} and {late} is not established")
            elif not before:
                lacking.append(f"{what} {early} was written after {then} {late}")
    return lacking


# --- the frame --------------------------------------------------------------------------------

# In the order a label is tried: a label that fits two elements belongs to the first.
ELEMENTS: dict[str, re.Pattern[str]] = {
    "case against": re.compile(
        r"(?i)case against|against (building|it|this|the idea)|strongest (case|argument|objection)"
        r"|counter-?argument|devil'?s advocate|reasons? not to|steel-?man"
    ),
    "stop rule": re.compile(
        r"(?i)stop rule|stop (if|when|condition|criteri|signal)|kill (rule|criteri|condition)"
        r"|when to stop|walk away|exit criteri|end the idea|ends? the idea"
    ),
    "appetite": re.compile(
        r"(?i)appetite|budget|time-?box|willing to spend|how much (time|money)|investment"
    ),
    "no-gos": re.compile(
        r"(?i)no-?gos?|non-?goals?|out of scope|not doing|will not do|exclusions?|bounds"
        r"|boundaries|won'?t do"
    ),
    "assumptions": re.compile(r"(?i)assumption|riskiest|hypothes|unknowns?|\bbets\b"),
    "first-version bar": re.compile(
        r"(?i)first[- ]version|\bv1\b|version 1|minimum|\bmvp\b|\bbar\b|done when"
        r"|definition of done|success (bar|criteri)|first release|good enough"
    ),
    "what they do today": re.compile(
        r"(?i)today|status quo|existing|alternative|instead|competit|currently|already"
    ),
    "outcome": re.compile(
        r"(?i)outcome|who (it|this|the product) is for|for whom|target (user|customer|audience)"
        r"|audience|who it serves"
    ),
}
# What only a full frame holds: a note with two of these frames the idea, whatever else it holds.
QUESTIONING = ("case against", "stop rule", "assumptions")

HEADING = re.compile(r"^\s{0,3}#{1,6}\s+(.+?)\s*#*\s*$")
BOLD = re.compile(r"^\s*(?:[-*+]\s+|\d+[.)]\s+)?(?:\*\*|__)([^*_]{2,80}?)(?:\*\*|__)")
COLON = re.compile(r"^\s*(?:[-*+]\s+)?([A-Za-z][A-Za-z0-9 '\u2019/&()\-]{1,60}?):(?:\s|$)")
ROW = re.compile(r"^\s*\|\s*([^|]+?)\s*\|")


def _label(line: str) -> str | None:
    for form in (HEADING, BOLD, COLON, ROW):
        found = form.match(line)
        if found:
            return found.group(1)
    return None


def labels(text: str) -> list[str]:
    """The label of each heading, bold lead, `label:` and table row in `text`."""

    return [found for line in text.splitlines() if (found := _label(line))]


def _element(label: str) -> str | None:
    return next((name for name, rule in ELEMENTS.items() if rule.search(label)), None)


def frame_elements(texts: Sequence[str]) -> dict[str, str]:
    """For each element of the frame the notes carry, the text from its label to the next
    element's label; the first note to carry an element is the one read."""

    found: dict[str, str] = {}
    for text in texts:
        lines = text.splitlines()
        marks = [
            (index, element)
            for index, line in enumerate(lines)
            if (label := _label(line)) and (element := _element(label))
        ]
        for position, (index, element) in enumerate(marks):
            end = marks[position + 1][0] if position + 1 < len(marks) else len(lines)
            found.setdefault(element, "\n".join(lines[index:end]))
    return found


FLAGGED = re.compile(
    r"(?i)\?|assum|unverified|unknown|\bask|\btbd\b|not (stated|given|specified)|unspecified"
    r"|open question|to confirm|\bconfirm|you (tell|decide|choose)|your (budget|time|call|answer)"
)
RANKING = re.compile(
    r"(?i)riskiest|ranked|\brank|most (risky|uncertain|likely)|highest[- ]risk|in order|priority"
)
LIST_ITEM = re.compile(r"(?m)^\s*(?:[-*+]|\d+[.)]|\|)\s*\S")


def is_ranked(body: str) -> bool:
    """Two or more assumptions, numbered or said to be in an order."""

    head, _, rest = body.partition("\n")
    items = len(LIST_ITEM.findall(rest)) + len(re.findall(r"(?:^|\s)\d[.)]\s", head))
    numbered = bool(re.search(r"(?m)^\s*\d+[.)]\s", rest)) or bool(re.search(r"\s2[.)]\s", head))
    return items >= 2 and (numbered or bool(RANKING.search(body)))


# --- the answer -------------------------------------------------------------------------------

_LABEL_WORDS = r"recommend\w*|verdict|my call|bottom line|conclusion"
_CHOICES = (
    ("stop", re.compile(r"(?i)\bstop\b|do(es)? not build|don'?t build|not build|abandon|\bkill\b")),
    ("probe", re.compile(r"(?i)probe|spike|prototype|validate first|test first")),
    ("build", re.compile(r"(?i)\bbuild(ing)?\b|\bproceed\b|go ahead")),
)


def recommendation(text: str) -> str | None:
    """`stop`, `probe` or `build`: the first choice named after a word that gives a verdict."""

    lines = text.splitlines()
    for index, line in enumerate(lines):
        marked = re.search(f"(?i)(?:{_LABEL_WORDS})", line)
        if not marked or re.search(
            r"(?i)(?:\bnot|n't|\bnever)\s+(?:\w+\s+)?$", line[: marked.start()]
        ):
            continue  # no verdict, or one that says what it does not recommend
        tail = " ".join([line[marked.end() :], *lines[index + 1 : index + 3]])
        hits = [(rule.search(tail), name) for name, rule in _CHOICES]
        named = sorted((hit.start(), name) for hit, name in hits if hit)
        if named:
            return named[0][1]
    return None


def blocks(text: str) -> list[str]:
    """Paragraphs and list items (a list item with the lines that continue it); a heading is not
    one."""

    found: list[list[str]] = []
    current: list[str] = []
    for line in text.splitlines():
        if not line.strip() or line.lstrip().startswith("#"):
            current = []
        elif re.match(r"^\s*(?:[-*+]|\d+[.)]|\|)\s", line) or not current:
            current = [line]
            found.append(current)
        else:
            current.append(line)
    return ["\n".join(block) for block in found]


TIES_TO_A_DECISION = re.compile(
    r"(?i)\b(changes?|changed|decid\w*|depends?|determines?|affects?|so (that )?(i|we)|otherwise"
    r"|if (you|yes|no|it|the|so)|then (i|we)|whether (i|we)|stop rule|appetite|no-?go"
    r"|recommend\w*|assum\w*)\b"
)


def bare_questions(text: str) -> list[str]:
    """The questions put to the person that name no decision their answer changes: a numbered
    item with a question mark, or a block that ends a line with one."""

    bare = []
    for block in blocks(text):
        numbered = re.match(r"^\s*\d+[.)]\s", block) is not None
        ends = any(
            re.sub(r"[\s*_`)\]\"'\u201d\u2019]+$", "", line).endswith("?")
            for line in block.splitlines()
        )
        if "?" in block and (numbered or ends) and not TIES_TO_A_DECISION.search(block):
            bare.append(" ".join(block.split())[:120])
    return bare


def has_status_line(text: str, subject: re.Pattern[str], status: str = "UNVERIFIED") -> bool:
    return any(status in block and subject.search(block) for block in blocks(text))


# --- the Done command -------------------------------------------------------------------------

DONE = re.compile(r"(?im)^\s*(?:[-*+]\s+)?(?:\*\*)?done(?:\*\*)?\s*:\s*(.*)$")
CHECK_WORDS = re.compile(r"(?i)test|check|assert|verify|lint|unittest|pytest")
DONE_TIMEOUT = 90


def done_commands() -> list[str]:
    """The commands that AGENTS.md or README.md records on a `Done:` line, in order."""

    found: list[str] = []
    for note in ("AGENTS.md", "README.md"):
        try:
            text = read(note)
        except OSError:
            continue
        for line in DONE.findall(text):
            found.extend(re.findall(r"`([^`]+)`", line))
    return list(dict.fromkeys(found))


CHECK_CONTENT = re.compile(
    r"(?m)\bdef test_|\bunittest\b|\bpytest\b|^\s*assert\b|\bassert[A-Z]\w*\("
)


def has_check(paths: Sequence[str]) -> bool:
    """Whether a changed code file is named for a test or a check, or holds an assertion."""

    return any(
        is_code(path)
        and (re.search(r"(?i)test|check", Path(path).name) or CHECK_CONTENT.search(read(path)))
        for path in paths
    )


def copy_workspace(destination: Path) -> Path:
    target = destination / "workspace"
    shutil.copytree(".", target, symlinks=True)
    return target


def run_in(command: str, root: Path) -> int | None:
    """The exit status of `command` run by a shell in `root`; None where it ran out of time."""

    env = {**os.environ, "PYTHONDONTWRITEBYTECODE": "1"}
    try:
        done = subprocess.run(
            ["sh", "-c", command],
            cwd=root,
            capture_output=True,
            timeout=DONE_TIMEOUT,
            env=env,
            stdin=subprocess.DEVNULL,
        )
    except subprocess.TimeoutExpired:
        return None
    return done.returncode


def break_product(root: Path) -> list[Path]:
    """Append a syntax error to each Python module of the product in `root`, which is not a test
    or a check; the files broken."""

    skipped = {".git", ".agents", ".outcomebound", "checks", "tests", "docs", *BYPRODUCTS}
    broken = []
    for path in sorted(root.rglob("*.py")):
        relative = path.relative_to(root)
        name = relative.name
        if skipped & set(relative.parts) or name.startswith("test_") or name.endswith("_test.py"):
            continue
        with path.open("a", encoding="utf-8") as handle:
            handle.write("\n)\n")
        broken.append(path)
    return broken


# --- running a probe --------------------------------------------------------------------------


def main(program: str, checks: dict[str, Callable[[], list[str]]], argv: list[str]) -> int:
    """Run the one check `argv` names; exit 0 where it holds, 1 printing why not, 2 on usage."""

    if len(argv) != 1 or argv[0] not in checks:
        print(f"usage: {program} {{{','.join(checks)}}}")
        return 2
    try:
        lacking = checks[argv[0]]()
    except Exception as problem:  # a broken workspace is a failed claim, never a crash
        lacking = [f"the check could not run: {type(problem).__name__}: {problem}"]
    for reason in lacking:
        print(reason)
    return 1 if lacking else 0


def scratch() -> tempfile.TemporaryDirectory[str]:
    return tempfile.TemporaryDirectory(prefix="new-project-check-")


if __name__ == "__main__":
    print("a library for the checks of the new-project fixtures", file=sys.stderr)
    raise SystemExit(2)
