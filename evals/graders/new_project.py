SCRIPT = re.compile(r"(?i)/|\.(sh|py|js|rb|bat|ps1)$")


def _recorded_on(rest: str) -> list[str]:
    """The Done commands that the text after `Done:` records. Where it has code spans, the first
    is the command, with the spans that a plain "and" or "," joins to it (not a set-up or start
    command that follows in other words). Where it has none, the text up to where prose follows
    is the one command, if its first word, past any `NAME=value`, is a runner (`python3`, `make`,
    `sh`) or a path to a script: a sentence ("the suite passes") records none."""

    spans = list(CODE_SPAN.finditer(rest))
    if spans:
        found = [spans[0].group(1)]
        for before, span in pairwise(spans):
            if not JOINING.fullmatch(rest[before.end() : span.start()]):
                break
            found.append(span.group(1))
        return found
    text = PROSE.split(rest, maxsplit=1)[0].strip().strip("* ")
    words = [word for word in text.split() if not re.fullmatch(r"[A-Za-z_]\w*=\S*", word)]
    if words and (words[0] in RUNNERS or SCRIPT.search(words[0])):
        return [text]
    return []


def done_commands() -> list[str]:
    """The commands that AGENTS.md or README.md records on a `Done:` line, in order."""

    found: list[str] = []
    for note in ("AGENTS.md", "README.md"):
        try:
            text = read(note)
        except OSError:
            continue
        for line in DONE.findall(text):
            found.extend(_recorded_on(line))
    return list(dict.fromkeys(found))


CHECK_CONTENT = re.compile(
    r"(?m)\bdef test_|\bunittest\b|\bpytest\b|^\s*assert\b|\bassert[A-Z]\w*\("
)


def has_check(paths: Sequence[str]) -> bool:
    """Whether a changed code file is named for a test or a check, or holds an assertion."""

    return any(
        is_code(path)
        and (re.search(r"(?i)test|check", Path(path).name) or CHECK_CONTENT.search(read(path)))
        for path in paths
    )


def copy_workspace(destination: Path) -> Path:
    target = destination / "workspace"
    shutil.copytree(".", target, symlinks=True)
    return target


def run_in(command: str, root: Path) -> int | None:
    """The exit status of `command` run by a shell in `root`; None where it ran out of time."""

    env = {**os.environ, "PYTHONDONTWRITEBYTECODE": "1"}
    try:
        done = subprocess.run(
            ["sh", "-c", command],
            cwd=root,
            capture_output=True,
            timeout=DONE_TIMEOUT,
            env=env,
            stdin=subprocess.DEVNULL,
        )
    except subprocess.TimeoutExpired:
        return None
    return done.returncode


def break_product(root: Path) -> list[Path]:
    """Append a syntax error to each Python module of the product in `root`, which is not a test
    or a check; the files broken."""

    skipped = {".git", ".agents", ".outcomebound", "checks", "tests", "docs", *BYPRODUCTS}
    broken = []
    for path in sorted(root.rglob("*.py")):
        relative = path.relative_to(root)
        name = relative.name
        if skipped & set(relative.parts) or name.startswith("test_") or name.endswith("_test.py"):
            continue
        with path.open("a", encoding="utf-8") as handle:
            handle.write("\n)\n")
        broken.append(path)
    return broken


