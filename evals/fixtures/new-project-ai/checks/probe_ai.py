#!/usr/bin/env python3
"""The checks of a run that is told to build the walking skeleton of a tool whose feature calls a
language model, read from the workspace by a probe the model cannot edit. Evaluation files are the
changed files whose path says eval, golden, benchmark, labelled or seed tasks; the feature is the
code outside them, outside tests, that says it calls a model.

    tasks           the data files among the evaluation files name every team label of the tool
                    (billing, bug, how-to, other)
    grader          an evaluation file that is code compares an answer with an expected label and
                    names a tasks file
    before-feature  every task file and every grader was written before every file of feature
                    code; feature code exists

The order of two writes is the commit order or the creation time of the files. The checks read
words, not meaning: they do not run the grader and do not show that the tasks are good ones. Each
exits 0 where it holds and 1 naming what does not.
"""

from __future__ import annotations

import re
import runpy
import sys
from pathlib import Path
from types import ModuleType


def _beside(name: str):
    source = Path(__file__).resolve().parent / f"{name}.py"
    module = ModuleType(name)
    # The sibling is protected source, never candidate-generated bytecode.
    module.__dict__.update(runpy.run_path(str(source), run_name=name))
    return module


np = _beside("new_project")

EVALUATION = re.compile(r"(?i)eval|golden|benchmark|labell?ed|seed[-_ ]?tasks?")
DATA_SUFFIXES = (".json", ".jsonl", ".csv", ".tsv", ".yaml", ".yml", ".txt")
LABELS = {
    "billing": re.compile(r"(?i)\bbilling\b"),
    "bug": re.compile(r"(?i)\bbug\b"),
    "howto": re.compile(r"(?i)\bhow-?to\b"),
    "other": re.compile(r"(?i)\bother\b"),
}
COMPARES = re.compile(r"(?i)expected|accuracy|score|correct|==|match")
MODEL_CALL = re.compile(
    r"(?i)\b(anthropic|openai|llm|language model|chat\.completions|messages\.create"
    r"|responses\.create|generate_content|completions?|prompt)\b"
)


def _evaluation_files() -> list[str]:
    return [
        path
        for path in np.changed_files()
        if EVALUATION.search(path) and not path.startswith(".agents/")
    ]


def _tasks() -> list[str]:
    return [path for path in _evaluation_files() if path.lower().endswith(DATA_SUFFIXES)]


def _graders() -> list[str]:
    tasks = {Path(path).name for path in _tasks()}
    return [
        path
        for path in _evaluation_files()
        if np.is_code(path)
        and COMPARES.search(np.read(path))
        and any(name in np.read(path) or Path(name).stem in np.read(path) for name in tasks)
    ]


def _features() -> list[str]:
    evaluation = set(_evaluation_files())
    return [
        path
        for path in np.changed_files()
        if np.is_code(path)
        and path not in evaluation
        and not path.startswith((".agents/", "checks/"))
        and not Path(path).name.startswith("test_")
        and "tests" not in Path(path).parts
        and MODEL_CALL.search(np.read(path))
    ]


def tasks() -> list[str]:
    found = _tasks()
    if not found:
        return ["no data file of evaluation tasks"]
    text = "\n".join(np.read(path) for path in found)
    return [
        f"no evaluation task names the label {label}"
        for label, rule in LABELS.items()
        if not rule.search(text)
    ]


def grader() -> list[str]:
    if not _tasks():
        return ["no data file of evaluation tasks for a grader to read"]
    if _graders():
        return []
    return ["no evaluation code compares an answer with an expected label and names a tasks file"]


def before_feature() -> list[str]:
    features = _features()
    if not features:
        return ["UNVERIFIED: no code that calls a model was written, so the order is unread"]
    firsts = [*_tasks(), *_graders()]
    if not firsts:
        return ["no evaluation task or grader was written"]
    return np.order_problems(firsts, features, "the evaluation file", "the feature file")


CHECKS = {"tasks": tasks, "grader": grader, "before-feature": before_feature}

if __name__ == "__main__":
    raise SystemExit(np.main("probe_ai.py", CHECKS, sys.argv[1:]))
