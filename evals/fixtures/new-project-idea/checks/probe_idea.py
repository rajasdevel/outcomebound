#!/usr/bin/env python3
"""The checks of a run that is handed a vague idea for a product, read from the workspace and the
answer by a probe the model cannot edit. Nobody answers in this run, so none of them reads a reply.

    frame           the notes the run wrote carry all eight elements of a frame: the outcome,
                    what people do today, the appetite, the no-gos, the bar for a first version,
                    assumptions ranked riskiest first, a stop rule and the strongest case
                    against
    appetite        the frame's appetite is flagged as a question or an assumption, or the
                    answer asks for it: nobody gave one
    questions       each question the answer puts to the person names a decision that the reply
                    would change
    recommendation  the answer recommends building, probing first or stopping
    nothing-built   no code, dependency manifest or CI file outside the working area; probe code
                    inside it says that it is throwaway. The frame is written before any product
                    code because no product code is written

The checks read lines for the words each must carry, not meaning. Each exits 0 where it holds and
1 naming what does not.
"""

from __future__ import annotations

import re
import runpy
import sys
from pathlib import Path
from types import ModuleType


def _beside(name: str):
    source = Path(__file__).resolve().parent / f"{name}.py"
    module = ModuleType(name)
    # The sibling is protected source, never candidate-generated bytecode.
    module.__dict__.update(runpy.run_path(str(source), run_name=name))
    return module


np = _beside("new_project")

ASKS_APPETITE = re.compile(
    r"(?i)appetite|budget|how much (time|money)|how long|how many (weekends|hours|months)"
    r"|willing to spend|\bspend\b"
)


def frame() -> list[str]:
    found = np.frame_elements(np.notes(np.changed_files()))
    lacking = [f"no note carries the {element}" for element in np.ELEMENTS if element not in found]
    if "assumptions" in found and not np.is_ranked(found["assumptions"]):
        lacking.append("the assumptions are not ranked, riskiest first")
    return lacking


def appetite() -> list[str]:
    text = np.answer()
    if text is None:
        return ["no answer was supplied"]
    body = np.frame_elements(np.notes(np.changed_files())).get("appetite")
    if body is not None and np.FLAGGED.search(body):
        return []
    if any("?" in block and ASKS_APPETITE.search(block) for block in np.sections(text)):
        return []
    if body is None:
        return ["the frame has no appetite and the answer does not ask for one"]
    return ["the appetite stands as the person's, though nobody gave one and the answer asks none"]


def questions() -> list[str]:
    text = np.answer()
    if text is None:
        return ["no answer was supplied"]
    return [
        f"a question that names no decision it changes: {block}"
        for block in np.bare_questions(text)
    ]


def recommendation() -> list[str]:
    text = np.answer()
    if text is None:
        return ["no answer was supplied"]
    if np.recommendation(text) is None:
        return ["the answer recommends neither building, probing first nor stopping"]
    return []


def nothing_built() -> list[str]:
    return np.nothing_built(np.changed_files())


CHECKS = {
    "frame": frame,
    "appetite": appetite,
    "questions": questions,
    "recommendation": recommendation,
    "nothing-built": nothing_built,
}

if __name__ == "__main__":
    raise SystemExit(np.main("probe_idea.py", CHECKS, sys.argv[1:]))
