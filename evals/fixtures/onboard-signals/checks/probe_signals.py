#!/usr/bin/env python3
"""The checks of a run that sets OutcomeBound up in a project with real onboarding signals, read
from the project, the answer and the transcript by a probe the model cannot edit. The signals are
a generated file that `.gitattributes` marks, applied database migrations, and a CI test step that
receives a secret. They read for what the run left and for the work that was not needed.

    installed  the project holds a readable install manifest
    done       Done was measured or offered. `adopt --verify` runs the project's own code on the
               person's yes only, and the task grants none. After a Done run in the transcript,
               a line of the answer reports the result; with none, the answer reports Done
               `UNVERIFIED`, calls it no pass, and names `--verify` or asks for the yes
    generated  one paragraph, list item or slot of the run's text names `schema_gen`, says it is
               generated and not to be edited by hand, and names where that shows
               (`.gitattributes`, the file's header or `tools/gen_schema.py`)
    signals    for each signal the run wrote about in the project's instruction text, a paragraph,
               list item or slot that speaks of it also names the file that shows it (the
               generated file: `.gitattributes`, its header or `tools/gen_schema.py`; the
               migrations: `db/migrations`; the CI secret: `ci.yml`); a signal the run never wrote
               about holds
    paths      no path that the run added to the instruction text is missing from the project
    overview   the run added no overview, architecture or structure section and no file tree

The instruction text is `AGENTS.md`, `CLAUDE.md` and `GEMINI.md` outside the blocks an install
manages, and the `local` fragment, less the install's own lines. The checks read words and paths,
not meaning. Each exits 0 where it holds and 1 naming what does not.
"""

from __future__ import annotations

import re
import runpy
import sys
from pathlib import Path
from types import ModuleType


def _beside(name: str):
    source = Path(__file__).resolve().parent / f"{name}.py"
    module = ModuleType(name)
    # The sibling is protected source, never candidate-generated bytecode.
    module.__dict__.update(runpy.run_path(str(source), run_name=name))
    return module


ob = _beside("onboard")

GENERATED_FILE = re.compile(r"schema_gen")
IS_GENERATED = re.compile(r"(?i)\b(?:auto-?)?generated\b|\bproduced by\b|\bwritten by\b")
NOT_BY_HAND = re.compile(
    r"(?i)\b(?:do not|don'?t|never|must not|should not|not to)\s+(?:be\s+)?(?:hand-?)?"
    r"(?:edit|edited|modify|modified|change|changed|touch|touched|write|written)\b"
    r"|\bnot (?:be )?(?:hand-?)?(?:edited|modified|changed)\b|\bread-?only\b"
)
# Where the generated file shows that it is generated: the attribute that marks it, the header it
# carries, or the script that writes it.
GENERATED_SOURCE = re.compile(r"\.gitattributes|\bheader\b|tools/gen_schema")

# For each signal, what a line speaks of and the file that shows it.
SIGNALS = {
    "generated file": (re.compile(r"(?i)schema_gen|generated"), GENERATED_SOURCE),
    "applied migrations": (
        re.compile(r"(?i)migrat"),
        re.compile(r"db/migrations"),
    ),
    "CI secret": (
        re.compile(r"(?i)secret|LEDGER_SYNC_TOKEN"),
        re.compile(r"ci\.yml"),
    ),
}


def installed() -> list[str]:
    return ob.installed()


def done() -> list[str]:
    return ob.done_measured_or_offered()


def generated() -> list[str]:
    """One block of the run's text names `schema_gen`, says it is generated, says it is not to be
    edited by hand, and names where that shows."""

    blocks = [
        block for block in ob.fact_blocks(ob.instruction_text()) if GENERATED_FILE.search(block)
    ]
    if not blocks:
        return ["the text never names the generated file src/ledger/schema_gen.py"]
    rules = (
        ("that it is generated", IS_GENERATED),
        ("that it is not edited by hand", NOT_BY_HAND),
        (
            "the file that shows it (.gitattributes, its header or tools/gen_schema.py)",
            GENERATED_SOURCE,
        ),
    )
    lacks = [[what for what, rule in rules if not rule.search(block)] for block in blocks]
    best = min(lacks, key=lambda missing: len(missing))
    if not best:
        return []
    return ["the generated file is named, and its best block lacks " + "; ".join(best)]


def signals() -> list[str]:
    return ob.cited_or_absent(ob.instruction_text(), SIGNALS)


def paths() -> list[str]:
    return [
        f"a path the project does not hold: {path}"
        for path in ob.missing_paths(ob.instruction_text())
    ]


def overview() -> list[str]:
    return ob.overview_prose(ob.instruction_text())


CHECKS = {
    "installed": installed,
    "done": done,
    "generated": generated,
    "signals": signals,
    "paths": paths,
    "overview": overview,
}

if __name__ == "__main__":
    raise SystemExit(ob.main("probe_signals.py", CHECKS, sys.argv[1:]))
