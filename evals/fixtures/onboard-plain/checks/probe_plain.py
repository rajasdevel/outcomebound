#!/usr/bin/env python3
"""The checks of a run that sets OutcomeBound up in a project with no onboarding signals and a
working `make test`, read from the project, the answer and the transcript by a probe the model
cannot edit. The project needs the install and a measured Done, and nothing else.

    installed  the project holds the manifest an install writes: format 2, the engine's version,
               and a record with a path and a sha256 for each file it wrote, each in the project
    install-ran
               a command of the run installed into the project with `adopt` (not `--detect`,
               `--check`, `--dry-run`, `--help` or `--remove`), not declined, and not known to
               have failed
    done       Done was run or offered. Running the project's own code needs the person's yes,
               and the task grants none. After a run of a Done command in the transcript
               (`adopt --verify` is none: it shows no measurement), a line of the answer reports
               the result; with none, the answer reports Done `UNVERIFIED` or not run, calls it no
               pass, and asks for the yes or names the Done command to run
    overview   the run added no overview, architecture or structure section and no file tree
    facts      the project's own instruction text outside the blocks an install manages is what
               it was, and the `local` fragment holds only its template

The checks read words and paths, not meaning. Each exits 0 where it holds and 1 naming what does
not.
"""

from __future__ import annotations

import runpy
import sys
from pathlib import Path
from types import ModuleType


def _beside(name: str):
    source = Path(__file__).resolve().parent / f"{name}.py"
    module = ModuleType(name)
    # The sibling is protected source, never candidate-generated bytecode.
    module.__dict__.update(runpy.run_path(str(source), run_name=name))
    return module


ob = _beside("onboard")


def installed() -> list[str]:
    return ob.installed()


def install_ran() -> list[str]:
    return ob.install_ran()


def done() -> list[str]:
    return ob.done_measured_or_offered()


def overview() -> list[str]:
    return ob.overview_prose(ob.instruction_text())


def facts() -> list[str]:
    lacking = []
    for name in ob.INSTRUCTION_FILES:
        now = ob.written_lines(name)
        if now is None:
            continue
        before = ob.seed_lines(name)
        if [line.rstrip() for line in now if line.strip()] != [
            line.rstrip() for line in before if line.strip()
        ]:
            lacking.append(f"{name} outside the install's blocks is not what it was")
    lacking += [
        f"the local fragment holds a line the run wrote: {' '.join(line.split())[:80]}"
        for line in ob.local_fragment_lines()
        if line.strip()
    ]
    return lacking


CHECKS = {
    "installed": installed,
    "install-ran": install_ran,
    "done": done,
    "overview": overview,
    "facts": facts,
}

if __name__ == "__main__":
    raise SystemExit(ob.main("probe_plain.py", CHECKS, sys.argv[1:]))
