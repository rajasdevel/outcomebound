"""Build the chatsvc project into a folder, with the history a team would have left.

    python3 -B chatsvc_build.py history <target>
        the project up to the last release, commit by commit
    python3 -B chatsvc_build.py commit <target> <author> <message>
                                           a fixture's own commit of every change it made
    python3 -B chatsvc_build.py finish <target>    every file the target holds folded into its last
                                           commit, tagged `seed`

The project's files are under `project/`; a Python file there ends in `.py.in`, so that this
repository's own linters and type checker leave the fixture's code alone, and is written without
the `.in`. The feedback export is generated by `feedback_data.py`. Commit dates and authors are
fixed, so two builds give the same history up to the last commit.

Standard library only.
"""

