def project_files() -> dict[str, bytes]:
    """Every file of the project by its path in the built project."""

    found = {}
    for path in sorted(PROJECT.rglob("*")):
        if path.is_file() and "__pycache__" not in path.parts:
            name = path.relative_to(PROJECT).as_posix()
            found[re.sub(r"\.py\.in$", ".py", name)] = path.read_bytes()
    found["data/feedback.jsonl"] = feedback_data.lines(feedback_data.BASE).encode("utf-8")
    return found


def changelog(release: str | None) -> str:
    """The changelog as it stood at `release`: its sections up to that release; all of it for
    None (the next release begun)."""

    text = (PROJECT / "CHANGELOG.md").read_text(encoding="utf-8")
    if release is None:
        return text
    head, *sections = re.split(r"(?m)^(?=## )", text)
    kept = []
    for section in sections:
        number = section.split()[1]
        released = number[0].isdigit() and "unreleased" not in section.splitlines()[0]
        if released and tuple(map(int, number.split("."))) <= tuple(map(int, release.split("."))):
            kept.append(section)
    return head + "".join(kept)


def git(target: Path, *args: str, when: str | None = None, author: str = "platform") -> str:
    env = {**os.environ, "GIT_CONFIG_GLOBAL": os.devnull, "GIT_CONFIG_NOSYSTEM": "1"}
    if when:
        name, email = AUTHORS[author]
        env.update(
            GIT_AUTHOR_DATE=when + "+00:00",
            GIT_COMMITTER_DATE=when + "+00:00",
            GIT_AUTHOR_NAME=name,
            GIT_AUTHOR_EMAIL=email,
            GIT_COMMITTER_NAME=name,
            GIT_COMMITTER_EMAIL=email,
        )
    done = subprocess.run(
        ["git", *args], cwd=target, env=env, capture_output=True, text=True, encoding="utf-8"
    )
    if done.returncode != 0:
        raise SystemExit(f"git {' '.join(args)}: {done.stderr.strip()}")
    return done.stdout.strip()


def write(target: Path, name: str, data: bytes) -> None:
    path = target / name
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(data)
    if name.startswith("bin/"):
        path.chmod(0o755)


def history(target: Path) -> None:
    files = project_files()
    added: list[str] = []
    git(target, "init", "-q", "-b", "main")
    git(target, "config", "user.email", "eval@example.invalid")
    git(target, "config", "user.name", "OutcomeBound eval")
    git(target, "config", "commit.gpgsign", "false")
    for when, author, message, prefixes, release, tag in STEPS:
        names = [n for n in files if any(n.startswith(p) for p in prefixes)]
        for name in names:
            write(target, name, files[name])
        added.extend(names)
        (target / "VERSION").write_text(f"{release or NEXT}\n", encoding="utf-8")
        (target / "CHANGELOG.md").write_text(changelog(release), encoding="utf-8")
        git(target, "add", "--", "VERSION", "CHANGELOG.md", *names)
        git(target, "commit", "-q", "--allow-empty", "-m", message, when=when, author=author)
        if tag:
            git(target, "tag", f"v{release}", when=when, author=author)
    missing = sorted(set(files) - set(added) - {"CHANGELOG.md"})
    if missing:
        raise SystemExit(f"chatsvc_build.py: no step adds {', '.join(missing)}")


def commit(target: Path, message: str, author: str = "platform") -> None:
    """A fixture's own commit after the history: every change the target holds."""

    git(target, "add", "-A")
    git(target, "commit", "-q", "-m", message, when=LAST, author=author)


def finish(target: Path) -> None:
    """Fold every file the target holds into its last commit (the arm's files among them, which
    the runner wrote before the build), and tag it `seed`."""

    git(target, "add", "-A")
    git(target, "commit", "-q", "--amend", "--no-edit", when=LAST)
    git(target, "tag", "-f", "seed")


def main(argv: list[str]) -> int:
    if len(argv) == 4 and argv[0] == "commit":
        commit(Path(argv[1]), argv[3], argv[2])
        return 0
    if len(argv) != 2 or argv[0] not in ("history", "finish"):
        print(
            "usage: chatsvc_build.py history|finish <target> | commit <target> <author> <message>",
            file=sys.stderr,
        )
        return 2
    (history if argv[0] == "history" else finish)(Path(argv[1]))
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
