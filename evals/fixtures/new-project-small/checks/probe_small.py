#!/usr/bin/env python3
"""The checks of a run that is asked for a small script for one person, read from the workspace
and the answer by a probe the model cannot edit. The route for a new project has nothing to add
here beyond a Done command with one check, so these read for the work that was not needed.

    frame  no note carries two of a frame's questioning elements: the strongest case against, a
           stop rule, ranked assumptions
    spec   no spec, design note or decision record was written
    probe  no probe, spike or prototype was written, and no note has a probe section
    ci     no CI workflow was written
    done   AGENTS.md or README.md records a Done command, it names a check, a file holds a check,
           and it exits 0 in a copy of the workspace
    kind   a line of the answer says the script is throwaway or personal, as a choice made

The checks read lines for the words each must carry, not meaning. Each exits 0 where it holds and
1 naming what does not. The answer is the file OUTCOMEBOUND_EVAL_ANSWER names.
"""

from __future__ import annotations

import re
import runpy
import sys
from pathlib import Path
from types import ModuleType


def _beside(name: str):
    source = Path(__file__).resolve().parent / f"{name}.py"
    module = ModuleType(name)
    # The sibling is protected source, never candidate-generated bytecode.
    module.__dict__.update(runpy.run_path(str(source), run_name=name))
    return module


np = _beside("new_project")

KIND = re.compile(r"(?i)\b(throw-?away|one-?off|personal)\b")
CHOSEN = re.compile(r"(?i)assum|treat|kind|size|classif|this is|it is|is a|as a")


def frame() -> list[str]:
    found = np.frame_elements(np.notes(np.changed_files()))
    held = [element for element in np.QUESTIONING if element in found]
    if len(held) >= 2:
        return [f"a note frames the idea: it carries {', '.join(held)}"]
    return []


def spec() -> list[str]:
    return [
        f"a spec or design note was written: {path}"
        for path in np.changed_files()
        if np.is_design(path)
    ]


def probe() -> list[str]:
    paths = np.changed_files()
    lacking = [f"a probe was written: {path}" for path in paths if np.is_probe_named(path)]
    lacking += [
        f"a note has a probe section: {path}"
        for path in paths
        if np.is_note(path)
        and any(
            re.search(r"(?i)\b(probe|spike)\b", label) for label in np.labels(np.added_text(path))
        )
    ]
    return lacking


def ci() -> list[str]:
    return [f"a CI file was written: {path}" for path in np.changed_files() if np.is_ci(path)]


def done() -> list[str]:
    paths = np.changed_files()
    commands = np.done_commands()
    if not commands:
        return ["no Done command is recorded in AGENTS.md or README.md"]
    lacking = []
    if not any(np.CHECK_WORDS.search(command) for command in commands):
        lacking.append("no Done command names a check")
    if not np.has_check(paths):
        lacking.append("no file holds a check: no test, no assertion")
    with np.scratch() as directory:
        root = np.copy_workspace(Path(directory))
        for command in commands:
            status = np.run_in(command, root)
            if status != 0:
                lacking.append(
                    f"`{command}` {'ran out of time' if status is None else f'exited {status}'}"
                )
    return lacking


def kind() -> list[str]:
    text = np.answer()
    if text is None:
        return ["no answer was supplied"]
    if any(KIND.search(block) and CHOSEN.search(block) for block in np.sections(text)):
        return []
    return ["no line of the answer says the script is throwaway or personal"]


CHECKS = {"frame": frame, "spec": spec, "probe": probe, "ci": ci, "done": done, "kind": kind}

if __name__ == "__main__":
    raise SystemExit(np.main("probe_small.py", CHECKS, sys.argv[1:]))
