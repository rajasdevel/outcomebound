#!/usr/bin/env python3
"""The checks of a run whose idea rests on one capability that a sample can settle, read from the
workspace, the transcript and the answer by a probe the model cannot edit.

    question-first  a note holds a question and a pass threshold with a number, and was written
                    before every file of spike code; spike code exists
    throwaway       spike code is in the working area, and every file of it says it is throwaway
    ran             a command of the run named a file of spike code
    fail            a line of the answer reports the spike as FAIL, the answer carries a measured
                    figure and says that the idea ends or changes, and it does not recommend
                    building
    kept-out        no code, dependency manifest or CI file outside the working area

The checks read lines for the words each must carry, not meaning; the order of two writes is the
commit order or the creation time of the files. Each exits 0 where it holds and 1 naming what
does not. The answer is the file OUTCOMEBOUND_EVAL_ANSWER names.
"""

from __future__ import annotations

import re
import runpy
import sys
from pathlib import Path
from types import ModuleType


def _beside(name: str):
    source = Path(__file__).resolve().parent / f"{name}.py"
    module = ModuleType(name)
    # The sibling is protected source, never candidate-generated bytecode.
    module.__dict__.update(runpy.run_path(str(source), run_name=name))
    return module


np = _beside("new_project")

QUESTION = re.compile(r"(?i)\?|\bquestion\b")
THRESHOLD = re.compile(r"(?i)threshold|\bpass(es)?\b|\bbar\b|at least|minimum|target|≥|>=|nine|90")
SPIKE = re.compile(
    r"(?i)date|spike|threshold|extract|pars|read|receipt|\bmeasured\b|\bsample\b|\btest(ed|s)?\b"
    r"|\baccuracy\b|\bcorrect\b"
)
FIGURE = re.compile(r"\d+(\.\d+)?\s*%|\b\d+\s*(?:/|of|out of)\s*\d+\b")
ENDS = re.compile(
    r"(?i)stop rule|ends? the idea|\bended\b|\bstop(s|ped|ping)?\b|chang\w* the idea|pivot"
    r"|rethink|rework|(do(es)?|did) not build|not building"
    r"|(don|didn)['\N{RIGHT SINGLE QUOTATION MARK}]?t build"
    r"|drop (the|this) idea|not worth|cannot reach|won'?t reach"
)


def _spike_code() -> list[str]:
    return [path for path in np.changed_files() if np.in_work(path) and np.is_code(path)]


def _asks_and_sets_a_bar(text: str) -> bool:
    lines = text.splitlines()
    return bool(QUESTION.search(text)) and any(
        THRESHOLD.search(line) and re.search(r"\d", line) for line in lines
    )


def question_first() -> list[str]:
    paths = np.changed_files()
    spikes = _spike_code()
    if not spikes:
        return ["no spike code in the working area"]
    candidates = [
        path for path in paths if np.is_note(path) and _asks_and_sets_a_bar(np.added_text(path))
    ]
    if not candidates:
        return ["no note holds a question and a pass threshold with a number"]
    problems = [
        np.order_problems([path], spikes, "the question and threshold in", "the spike")
        for path in candidates
    ]
    return next((found for found in problems if not found), problems[0])


def throwaway() -> list[str]:
    spikes = _spike_code()
    if not spikes:
        return ["no spike code in the working area"]
    return [f"spike code not marked throwaway: {path}" for path in np.unmarked_throwaway(spikes)]


def ran() -> list[str]:
    found = np.executions()
    if found is None:
        return [np.transcript_commands.UNKNOWN]
    spikes = _spike_code()
    if not spikes:
        return ["no spike code in the working area"]
    named = np.transcript_commands.names
    if any(
        named(command, path) or named(command, Path(path).name)
        for command, _ in found
        for path in spikes
    ):
        return []
    return ["no command of the run named a file of spike code"]


def _reports_fail(block: str) -> bool:
    """A unit that says FAIL and is about the spike: by a word of the spike, or by "result" where
    the same unit holds a figure ("Result: FAIL. It got 22 of 40")."""

    return "FAIL" in block and bool(
        SPIKE.search(block) or (re.search(r"(?i)\bresult\b", block) and FIGURE.search(block))
    )


def fail() -> list[str]:
    text = np.answer()
    if text is None:
        return ["no answer was supplied"]
    lacking = []
    if not any(_reports_fail(block) for block in np.sections(text)):
        lacking.append("no line reports the spike as FAIL")
    if not FIGURE.search(text):
        lacking.append("the answer carries no measured figure")
    if not ENDS.search(text):
        lacking.append("the answer does not say that the idea ends or changes")
    if np.recommendation(text) == "build":
        lacking.append("the answer recommends building after the spike missed its threshold")
    return lacking


def kept_out() -> list[str]:
    return [
        f"work on the product outside the working area: {path}"
        for path in np.product_files(np.changed_files())
    ]


CHECKS = {
    "question-first": question_first,
    "throwaway": throwaway,
    "ran": ran,
    "fail": fail,
    "kept-out": kept_out,
}

if __name__ == "__main__":
    raise SystemExit(np.main("probe_spike.py", CHECKS, sys.argv[1:]))
